"""Tests for API health check and error handling."""

from fastapi.testclient import TestClient
import pytest
from backend.main import app


def test_health_check_returns_ok():
    """Verify GET /api/health returns HTTP 200 and {'status': 'ok'}."""
    client = TestClient(app)
    response = client.get("/api/health")
    assert response.status_code == 200
    assert response.json() == {"status": "ok"}


def test_global_exception_handler():
    """Verify unhandled exceptions return 500 with generic error message.

    Starlette's TestClient defaults to raise_server_exceptions=True, which re-raises
    exceptions locally in test code. We pass raise_server_exceptions=False to receive
    the actual HTTP 500 JSONResponse generated by the global exception handler.
    """
    client = TestClient(app, raise_server_exceptions=False)

    @app.get("/api/test-error-endpoint-for-handler")
    def trigger_error():
        raise RuntimeError("Simulated internal error")

    response = client.get("/api/test-error-endpoint-for-handler")
    assert response.status_code == 500
    assert response.json() == {"error": "Something went wrong"}
